/**
 * Registration migration derivation.
 *
 * SQLite cannot ALTER a CHECK constraint, so every game registration
 * migration rebuilds the game_type-constrained tables with the extended
 * list (the 0049/0056/0059/0062/0064 table-copy pattern). The generator
 * derives the next migration mechanically from the latest registration
 * migration: same rebuild set, same table bodies, game_type lists
 * extended with the new id. Game-owned tables stay a marked manual
 * step — the emitted file ends with a TODO section for them.
 */

const MIGRATION_FILE_PATTERN = /^(\d{4})_[a-z0-9_]+\.sql$/;

/** Pick the next migration number and file name from the existing directory listing. */
export function nextMigrationName(fileNames, gameId) {
  let max = 0;
  for (const name of fileNames) {
    const match = MIGRATION_FILE_PATTERN.exec(name);
    if (match !== null) max = Math.max(max, Number.parseInt(match[1], 10));
  }
  if (max === 0) throw new Error('No existing migrations found; cannot derive the next number.');
  return `${String(max + 1).padStart(4, '0')}_${gameId}.sql`;
}

/** Find the latest migration that rebuilds the rooms game_type CHECK (the registration pattern). */
export function findLatestRegistrationMigration(files) {
  const candidates = files
    .filter(({ name }) => MIGRATION_FILE_PATTERN.test(name))
    .sort((a, b) => a.name.localeCompare(b.name));
  for (let index = candidates.length - 1; index >= 0; index -= 1) {
    const candidate = candidates[index];
    if (candidate.content.includes('game_type IN (') && candidate.content.includes('rooms_next')) {
      return candidate;
    }
  }
  throw new Error('No registration migration (rooms rebuild with a game_type CHECK) found.');
}

/** Extend every game_type CHECK list in the source migration with the new id. */
export function extendGameTypeLists(content, gameId) {
  const listPattern = /game_type IN \(([^)]*)\)/g;
  const matches = [...content.matchAll(listPattern)];
  if (matches.length === 0) throw new Error('Source migration carries no game_type CHECK list.');
  let extended = content;
  for (const match of matches) {
    if (match[1].includes(`'${gameId}'`)) {
      throw new Error(`Source migration already lists '${gameId}'.`);
    }
  }
  extended = extended.replace(listPattern, (_m, list) => `game_type IN (${list}, '${gameId}')`);
  return extended;
}

/** Build the registration migration for the new game from the latest one. */
export function buildRegistrationMigration({ sourceName, sourceContent, gameId, displayName }) {
  const extended = extendGameTypeLists(sourceContent, gameId);
  const bodyStart = extended.indexOf('PRAGMA defer_foreign_keys = true;');
  if (bodyStart < 0) throw new Error(`Source migration ${sourceName} has no PRAGMA body start.`);
  const body = extended.slice(bodyStart);
  const header = [
    `-- Register ${displayName} (${gameId}) in the room directory game-type`,
    `-- constraints. ${gameId} needs no new tables yet (game-owned tables are`,
    `-- a TODO below, to be filled in with the gameplay design).`,
    `--`,
    `-- Generated by \`pnpm new-game\` from ${sourceName}: follows the`,
    `-- table-copy pattern — SQLite cannot ALTER a CHECK constraint, so rooms`,
    `-- and product_game_reward_results are rebuilt with the extended`,
    `-- game_type list, plus their foreign-key dependents. REVIEW BY HAND`,
    `-- before applying: confirm the rebuild set still matches the schema.`,
    ``,
  ].join('\n');
  const todo = [
    ``,
    `-- TODO(gameplay): add the game-owned tables for ${gameId} here (if any),`,
    `-- following the per-game table pattern of the word/media games. A game`,
    `-- with no owned tables needs nothing beyond the rebuilds above.`,
    ``,
  ].join('\n');
  return `${header}${body}${todo}`;
}
