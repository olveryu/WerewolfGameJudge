#!/usr/bin/env node
/**
 * Generate host adapters from the repository's canonical agent configuration.
 *
 * Canonical sources:
 *   - AGENTS.md
 *   - agents/path-rules/*.md
 *   - .agents/skills/<name>/**
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { parseDocument, stringify } from 'yaml';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const AGENTS_MD = path.join(ROOT, 'AGENTS.md');
const PATH_RULES_DIR = path.join(ROOT, 'agents', 'path-rules');
const SKILLS_SOURCE = path.join(ROOT, '.agents', 'skills');

const GENERATED_NOTICE =
  '<!-- GENERATED by `pnpm run sync:agents`; edit AGENTS.md, agents/path-rules/, or .agents/skills/. -->';
const MANAGED_DIRECTORIES = ['.github/instructions', '.cursor/rules', '.claude/skills'];
const OBSOLETE_OUTPUTS = [
  '.github/copilot-instructions.md',
  '.github/prompts',
  '.github/skills',
  '.cursor/skills',
  'skills',
];
const PATH_RULE_METADATA_KEYS = new Set(['name', 'description', 'applyTo']);
const SKILL_METADATA_KEYS = new Set([
  'name',
  'description',
  'license',
  'compatibility',
  'metadata',
  'allowed-tools',
]);

function compareNames(leftName, rightName) {
  if (leftName < rightName) return -1;
  if (leftName > rightName) return 1;
  return 0;
}

function getAbsolutePath(repositoryPath) {
  return path.join(ROOT, ...repositoryPath.split('/'));
}

async function pathExists(absolutePath) {
  try {
    await fs.access(absolutePath);
    return true;
  } catch (error) {
    if (error.code === 'ENOENT') return false;
    throw error;
  }
}

function assertNoReplacementCharacters(content, sourcePath) {
  if (content.includes('\uFFFD')) {
    throw new Error(`${sourcePath} contains Unicode replacement characters`);
  }
}

function parseFrontmatter(content, sourcePath) {
  const normalizedContent = content.replace(/\r\n/g, '\n');
  const match = normalizedContent.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!match) {
    throw new Error(`${sourcePath} must start with valid YAML frontmatter`);
  }

  const document = parseDocument(match[1], {
    logLevel: 'error',
    strict: true,
    stringKeys: true,
    uniqueKeys: true,
  });
  if (document.errors.length > 0) {
    throw new Error(`${sourcePath}: ${document.errors.map((error) => error.message).join('; ')}`);
  }
  if (document.warnings.length > 0) {
    throw new Error(
      `${sourcePath}: ${document.warnings.map((warning) => warning.message).join('; ')}`,
    );
  }

  const metadata = document.toJS({ maxAliasCount: 0 });
  if (!metadata || Array.isArray(metadata) || typeof metadata !== 'object') {
    throw new Error(`${sourcePath} frontmatter must be a mapping`);
  }

  return { metadata, body: match[2] };
}

function assertAllowedMetadata(metadata, allowedKeys, sourcePath) {
  const unsupportedKeys = Object.keys(metadata).filter((key) => !allowedKeys.has(key));
  if (unsupportedKeys.length > 0) {
    throw new Error(
      `${sourcePath} has unsupported frontmatter keys: ${unsupportedKeys.join(', ')}`,
    );
  }
}

function requireMetadataString(metadata, key, sourcePath) {
  const value = metadata[key];
  if (typeof value !== 'string' || value.trim() === '') {
    throw new Error(`${sourcePath} frontmatter field "${key}" must be a non-empty string`);
  }
  return value;
}

function serializeFrontmatter(metadata) {
  const yaml = stringify(metadata, {
    defaultStringType: 'QUOTE_SINGLE',
    lineWidth: 0,
    singleQuote: true,
  });
  return `---\n${yaml}---\n`;
}

function buildGeneratedDocument(metadata, body) {
  return `${serializeFrontmatter(metadata)}\n${GENERATED_NOTICE}\n\n${body.trim()}\n`;
}

function validatePathRule(content, sourcePath) {
  assertNoReplacementCharacters(content, sourcePath);
  const parsed = parseFrontmatter(content, sourcePath);
  assertAllowedMetadata(parsed.metadata, PATH_RULE_METADATA_KEYS, sourcePath);

  return {
    name: requireMetadataString(parsed.metadata, 'name', sourcePath),
    description: requireMetadataString(parsed.metadata, 'description', sourcePath),
    applyTo: requireMetadataString(parsed.metadata, 'applyTo', sourcePath),
    body: parsed.body,
  };
}

function validateSkill(content, sourcePath, skillDirectoryName) {
  assertNoReplacementCharacters(content, sourcePath);
  const { metadata } = parseFrontmatter(content, sourcePath);
  assertAllowedMetadata(metadata, SKILL_METADATA_KEYS, sourcePath);

  const name = requireMetadataString(metadata, 'name', sourcePath);
  const description = requireMetadataString(metadata, 'description', sourcePath);
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name) || name.length > 64) {
    throw new Error(`${sourcePath} has an invalid Agent Skills name`);
  }
  if (name !== skillDirectoryName) {
    throw new Error(`${sourcePath} name must match its parent directory`);
  }
  if (description.length > 1024) {
    throw new Error(`${sourcePath} description exceeds 1024 characters`);
  }
}

async function listFilesRecursively(absoluteDirectory, relativeDirectory = '') {
  const entries = (await fs.readdir(absoluteDirectory, { withFileTypes: true })).sort(
    (left, right) => compareNames(left.name, right.name),
  );
  const files = [];

  for (const entry of entries) {
    const relativePath = relativeDirectory
      ? path.posix.join(relativeDirectory, entry.name)
      : entry.name;
    const absolutePath = path.join(absoluteDirectory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listFilesRecursively(absolutePath, relativePath)));
    } else if (entry.isFile()) {
      files.push(relativePath);
    } else {
      throw new Error(`Unsupported filesystem entry: ${absolutePath}`);
    }
  }

  return files;
}

async function buildPathRuleOutputs(expectedOutputs) {
  if (!(await pathExists(PATH_RULES_DIR))) {
    throw new Error('Missing agents/path-rules/');
  }

  const pathRuleFiles = (await fs.readdir(PATH_RULES_DIR))
    .filter((fileName) => fileName.endsWith('.md'))
    .sort(compareNames);

  for (const fileName of pathRuleFiles) {
    const ruleId = fileName.slice(0, -'.md'.length);
    const sourcePath = `agents/path-rules/${fileName}`;
    const content = await fs.readFile(path.join(PATH_RULES_DIR, fileName), 'utf8');
    const rule = validatePathRule(content, sourcePath);

    expectedOutputs.set(
      `.github/instructions/${ruleId}.instructions.md`,
      buildGeneratedDocument(
        { name: rule.name, description: rule.description, applyTo: rule.applyTo },
        rule.body,
      ),
    );
    expectedOutputs.set(
      `.cursor/rules/${ruleId}.mdc`,
      buildGeneratedDocument(
        { description: rule.description, globs: rule.applyTo, alwaysApply: false },
        rule.body,
      ),
    );
  }

  return pathRuleFiles;
}

async function buildClaudeSkillOutputs(expectedOutputs) {
  if (!(await pathExists(SKILLS_SOURCE))) {
    throw new Error('Missing .agents/skills/');
  }

  const skillEntries = (await fs.readdir(SKILLS_SOURCE, { withFileTypes: true }))
    .filter((entry) => entry.isDirectory())
    .sort((left, right) => compareNames(left.name, right.name));

  for (const skillEntry of skillEntries) {
    const skillDirectory = path.join(SKILLS_SOURCE, skillEntry.name);
    const skillFile = path.join(skillDirectory, 'SKILL.md');
    if (!(await pathExists(skillFile))) {
      throw new Error(`Missing .agents/skills/${skillEntry.name}/SKILL.md`);
    }

    const skillContent = await fs.readFile(skillFile, 'utf8');
    validateSkill(skillContent, `.agents/skills/${skillEntry.name}/SKILL.md`, skillEntry.name);

    for (const relativeFile of await listFilesRecursively(skillDirectory)) {
      expectedOutputs.set(
        `.claude/skills/${skillEntry.name}/${relativeFile}`,
        await fs.readFile(path.join(skillDirectory, ...relativeFile.split('/'))),
      );
    }
  }
}

function buildClaudeEntrypoint(pathRuleFiles) {
  const pathRuleLinks = pathRuleFiles
    .map((fileName) => `- [agents/path-rules/${fileName}](agents/path-rules/${fileName})`)
    .join('\n');

  return `${GENERATED_NOTICE}

# Claude Code

> Edit [\`AGENTS.md\`](AGENTS.md), [\`agents/path-rules/\`](agents/path-rules/), or [\`.agents/skills/\`](.agents/skills/), then run \`pnpm run sync:agents\`.

## Project Instructions

@AGENTS.md

## Path Rules

Read the matching source rule before editing files in its scope:

${pathRuleLinks}

## Skills

Project skills are mirrored from [\`.agents/skills/\`](.agents/skills/) to [\`.claude/skills/\`](.claude/skills/) for native Claude Code discovery.

See [docs/agent-config.md](docs/agent-config.md).
`;
}

function buildGeminiEntrypoint() {
  return `${GENERATED_NOTICE}

# Gemini CLI

@AGENTS.md

Path rules live in \`agents/path-rules/\`. Project skills are discovered from \`.agents/skills/\`.

Run \`pnpm run sync:agents\` after editing canonical agent configuration. See [docs/agent-config.md](docs/agent-config.md).
`;
}

async function buildExpectedOutputs() {
  if (!(await pathExists(AGENTS_MD))) {
    throw new Error('Missing AGENTS.md at repository root');
  }
  const agentsContent = await fs.readFile(AGENTS_MD, 'utf8');
  assertNoReplacementCharacters(agentsContent, 'AGENTS.md');

  const expectedOutputs = new Map();
  const pathRuleFiles = await buildPathRuleOutputs(expectedOutputs);
  await buildClaudeSkillOutputs(expectedOutputs);
  expectedOutputs.set('CLAUDE.md', buildClaudeEntrypoint(pathRuleFiles));
  expectedOutputs.set('GEMINI.md', buildGeminiEntrypoint());
  return expectedOutputs;
}

async function findDrift(expectedOutputs) {
  const drift = [];

  for (const [repositoryPath, expectedContent] of expectedOutputs) {
    const absolutePath = getAbsolutePath(repositoryPath);
    if (!(await pathExists(absolutePath))) {
      drift.push(`missing: ${repositoryPath}`);
      continue;
    }
    const actualContent = await fs.readFile(absolutePath);
    const expectedBuffer = Buffer.isBuffer(expectedContent)
      ? expectedContent
      : Buffer.from(expectedContent, 'utf8');
    if (!actualContent.equals(expectedBuffer)) {
      drift.push(`outdated: ${repositoryPath}`);
    }
  }

  for (const managedDirectory of MANAGED_DIRECTORIES) {
    const absoluteDirectory = getAbsolutePath(managedDirectory);
    if (!(await pathExists(absoluteDirectory))) continue;
    for (const relativeFile of await listFilesRecursively(absoluteDirectory)) {
      const repositoryPath = path.posix.join(managedDirectory, relativeFile);
      if (!expectedOutputs.has(repositoryPath)) {
        drift.push(`stale: ${repositoryPath}`);
      }
    }
  }

  for (const obsoleteOutput of OBSOLETE_OUTPUTS) {
    if (await pathExists(getAbsolutePath(obsoleteOutput))) {
      drift.push(`obsolete: ${obsoleteOutput}`);
    }
  }

  return drift.sort(compareNames);
}

async function writeExpectedOutputs(expectedOutputs) {
  for (const managedDirectory of MANAGED_DIRECTORIES) {
    await fs.rm(getAbsolutePath(managedDirectory), { recursive: true, force: true });
  }
  for (const obsoleteOutput of OBSOLETE_OUTPUTS) {
    await fs.rm(getAbsolutePath(obsoleteOutput), { recursive: true, force: true });
  }

  const sortedOutputs = [...expectedOutputs.entries()].sort(([leftPath], [rightPath]) =>
    compareNames(leftPath, rightPath),
  );
  for (const [repositoryPath, content] of sortedOutputs) {
    const absolutePath = getAbsolutePath(repositoryPath);
    await fs.mkdir(path.dirname(absolutePath), { recursive: true });
    await fs.writeFile(absolutePath, content);
    console.log(`Synced ${repositoryPath}`);
  }
}

function parseMode(argumentsList) {
  const unsupportedArguments = argumentsList.filter((argument) => argument !== '--check');
  if (unsupportedArguments.length > 0) {
    throw new Error(`Unsupported arguments: ${unsupportedArguments.join(', ')}`);
  }
  return { isCheck: argumentsList.includes('--check') };
}

async function main() {
  const { isCheck } = parseMode(process.argv.slice(2));
  const expectedOutputs = await buildExpectedOutputs();

  if (isCheck) {
    const drift = await findDrift(expectedOutputs);
    if (drift.length > 0) {
      throw new Error(
        `Agent configuration drift detected:\n${drift.map((item) => `  - ${item}`).join('\n')}\nRun pnpm run sync:agents.`,
      );
    }
    console.log('Agent configuration is in sync');
    return;
  }

  await writeExpectedOutputs(expectedOutputs);
  const remainingDrift = await findDrift(expectedOutputs);
  if (remainingDrift.length > 0) {
    throw new Error(`Agent configuration sync failed:\n${remainingDrift.join('\n')}`);
  }
  console.log('Agent configuration sync complete');
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
